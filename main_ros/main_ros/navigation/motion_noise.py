"""Encoder noise analysis vs. commanded velocity (without ROS).

Common data format (written by motion_noise_test and generated by load_bag):
CSV with columns t, topic, a, b
    topic = 'cmd'   a = v [m/s], b = ω [rad/s]  (each /cmd_vel publication)
    topic = 'encR'  a = ω_R [rad/s]             (right wheel velocity)
    topic = 'encL'  a = ω_L [rad/s]             (left wheel velocity)

Process: (1) the recording is divided into segments with a constant, non-zero command;
(2) for each segment, the initial phase until the speed stabilizes is discarded (as is the final phase);
(3) within the stable window, the mean and standard deviation (noise amplitude, 1σ) are measured
for each wheel and for v and ω;
(4) segments with the same command (outward and return paths, repetitions) are grouped together; and
(5) the relationship σ = σ0 + k·|speed| is fitted.
"""

import csv
import math
import numpy as np

EPS_CMD = 1e-4

def load_log(path):
    data = {'cmd': [], 'encR': [], 'encL': []}
    with open(str(path), newline='') as f:
        for row in csv.DictReader(f):
            topic = row.get('topic')
            if topic not in data:
                continue
            try:
                t = float(row['t'])
                a = float(row['a'])
                b = float(row['b']) if row.get('b') not in (None, '') else 0.0
            except (TypeError, ValueError):
                continue
            data[topic].append((t, a, b))
    out = {}
    for k, rows in data.items():
        arr = np.array(sorted(rows), dtype=float).reshape(-1, 3)
        out[k] = arr
    return out

def write_log_header(f):
    w = csv.writer(f)
    w.writerow(['t', 'topic', 'a', 'b'])
    return w

def load_bag(path, cmd_topic='/cmd_vel', right_topic='/VelocityEncR', left_topic='/VelocityEncL', 
right_sign=1.0, left_sign=1.0):
    """Reads a rosbag2 (sqlite3 or mcap) in the same format as load_log. Requires ROS 2."""
    import rosbag2_py
    from rclpy.serialization import deserialize_message
    from rosidl_runtime_py.utilities import get_message

    storage = 'mcap' if str(path).endswith('.mcap') else ''
    reader = rosbag2_py.SequentialReader()
    reader.open(rosbag2_py.StorageOptions(uri=str(path), storage_id=storage), 
    rosbag2_py.ConverterOptions('', ''))
    types = {t.name: t.type for t in reader.get_all_topics_and_types()}
    for need in (cmd_topic, right_topic, left_topic):
        if need not in types:
            raise ValueError('The bag does not have %s (has: %s)' % (need, sorted(types)))
    msg_cls = {name: get_message(types[name]) for name in (cmd_topic, right_topic, left_topic)}
    data = {'cmd': [], 'encR': [], 'encL': []}
    while reader.has_next():
        topic, raw, t_ns = reader.read_next()
        if topic not in msg_cls:
            continue
        msg = deserialize_message(raw, msg_cls[topic])
        t = t_ns * 1e-9
        if topic == cmd_topic:
            data['cmd'].append((t, msg.linear.x, msg.angular.z))
        elif topic == right_topic:
            data['encR'].append((t, right_sign * msg.data, 0.0))
        else:
            data['encL'].append((t, left_sign * msg.data, 0.0))
    return {k: np.array(v, dtype=float).reshape(-1, 3) for k, v in data.items()}

# Segmentation
def segments(cmd, min_duration=1.5, tol=1e-3):
    """Segments of constant, non-zero command: list of (t0, t1, v, w)."""
    out = []
    if len(cmd) == 0:
        return out
    start = 0
    for i in range(1, len(cmd) + 1):
        changed = (i == len(cmd) or abs(cmd[i, 1] - cmd[start, 1]) > tol
        or abs(cmd[i, 2] - cmd[start, 2]) > tol)
        if changed:
            t0 = cmd[start, 0]
            t1 = cmd[i, 0] if i < len(cmd) else cmd[i - 1, 0]
            v, w = cmd[start, 1], cmd[start, 2]
            if (abs(v) > EPS_CMD or abs(w) > EPS_CMD) and t1 - t0 >= min_duration:
                out.append((t0, t1, float(v), float(w)))
            start = i
    return out

def kind_of(v, w, tol=1e-3):
    if abs(w) <= tol:
        return 'straight'
    if abs(v) <= tol:
        return 'turn'
    return 'curve'

def steady_start(t, x, t0, t1, settle_min, window=0.5, rel_tol=0.05, abs_tol=0.05):
    """First moment at which the moving average (window s) falls within the tolerance of the
    final speed, without occurring earlier than t0 + settle_min."""
    m = (t >= t0) & (t <= t1)
    tt, xx = t[m], x[m]
    if len(tt) < 5:
        return t0 + settle_min
    final = float(np.median(xx[tt >= t0 + (t1 - t0) / 2]))
    tol = max(rel_tol * abs(final), abs_tol)
    dt = np.median(np.diff(tt)) if len(tt) > 1 else 0.02
    n = max(1, int(round(window / max(dt, 1e-3))))
    if len(xx) <= n:
        return t0 + settle_min
    mov = np.convolve(xx, np.ones(n) / n, mode='valid')
    bad = np.abs(mov - final) > tol
    idx = np.nonzero(bad)[0]
    # First window from which there is no further exit
    first_ok = 0 if len(idx) == 0 else int(idx[-1]) + 1
    if first_ok >= len(mov):
        return float('nan')
    return max(t0 + settle_min, float(tt[first_ok + n - 1]))


def analyze_segment(data, seg, model, settle_min=1.0, tail=0.3):
    t0, t1, v_cmd, w_cmd = seg
    eR, eL = data['encR'], data['encL']
    wR_cmd, wL_cmd = model.twist_to_wheels(v_cmd, w_cmd)
    sR = steady_start(eR[:, 0], eR[:, 1], t0, t1, settle_min)
    sL = steady_start(eL[:, 0], eL[:, 1], t0, t1, settle_min)
    ws, we = max(sR, sL), t1 - tail
    res = {'t0': t0, 't1': t1, 'v_cmd': v_cmd, 'w_cmd': w_cmd, 'kind': kind_of(v_cmd, w_cmd),
           'wR_cmd': wR_cmd, 'wL_cmd': wL_cmd, 'win_start': ws, 'win_end': we,
           'settle_s': ws - t0 if math.isfinite(ws) else float('nan')}
    if not math.isfinite(ws) or we - ws < 0.5:
        res['ok'] = False
        res['why'] = 'Didn\'t stabilize or window < 0.5 s'
        return res
    mR = (eR[:, 0] >= ws) & (eR[:, 0] <= we)
    mL = (eL[:, 0] >= ws) & (eL[:, 0] <= we)
    if mR.sum() < 10 or mL.sum() < 10:
        res['ok'] = False
        res['why'] = 'Less than 10 encoder samples in the window'
        return res
    tR, xR = eR[mR, 0], eR[mR, 1]
    xL_on_R = np.interp(tR, eL[mL, 0], eL[mL, 1])
    v = model.r * (xR + xL_on_R) / 2.0
    w = model.r * (xR - xL_on_R) / model.L
    res.update({
        'ok': True, 'n': int(mR.sum()), 'rate_hz': float((len(tR) - 1) / max(tR[-1] - tR[0], 1e-6)),
        'wR_mean': float(xR.mean()), 'wR_std': float(xR.std(ddof=1)),
        'wL_mean': float(eL[mL, 1].mean()), 'wL_std': float(eL[mL, 1].std(ddof=1)),
        'wR_p2p': float(np.ptp(xR)), 'wL_p2p': float(np.ptp(eL[mL, 1])),
        'v_mean': float(v.mean()), 'v_std': float(v.std(ddof=1)),
        'w_mean': float(w.mean()), 'w_std': float(w.std(ddof=1)),
    })
    return res

def group_key(r, ndigits=3):
    """Ida y vuelta y repeticiones del mismo |comando| se agrupan."""
    return (r['kind'], round(abs(r['v_cmd']), ndigits), round(abs(r['w_cmd']), ndigits))


def pooled(results):
    """Agrupa tramos por |comando|. σ agrupada = sqrt(media de varianzas por tramo):
    no mezcla en el ruido la diferencia de medias entre ida y vuelta."""
    groups = {}
    for r in results:
        if r.get('ok'):
            groups.setdefault(group_key(r), []).append(r)
    out = []
    for (kind, v, w), rs in sorted(groups.items()):
        def pstd(key):
            return float(np.sqrt(np.mean([x[key] ** 2 for x in rs])))

        def amean(key):
            return float(np.mean([abs(x[key]) for x in rs]))
        out.append({
            'kind': kind, 'v_cmd': v, 'w_cmd': w, 'n_seg': len(rs),
            'n': int(sum(x['n'] for x in rs)),
            'wR_cmd': amean('wR_cmd'), 'wL_cmd': amean('wL_cmd'),
            'wR_mean': amean('wR_mean'), 'wL_mean': amean('wL_mean'),
            'wR_std': pstd('wR_std'), 'wL_std': pstd('wL_std'),
            'v_mean': amean('v_mean'), 'v_std': pstd('v_std'),
            'w_mean': amean('w_mean'), 'w_std': pstd('w_std'),
            'settle_s': float(np.nanmax([x['settle_s'] for x in rs])),
        })
    return out

def fit_linear(x, y):
    """y = a + b·x por mínimos cuadrados, a >= 0 y b >= 0. Devuelve (a, b, r2)."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    ok = np.isfinite(x) & np.isfinite(y)
    x, y = x[ok], y[ok]
    if len(x) == 0:
        return 0.0, 0.0, float('nan')
    if len(x) < 2 or np.ptp(x) < 1e-9:
        return float(np.mean(y)), 0.0, float('nan')
    b, a = np.polyfit(x, y, 1)
    if b < 0:
        a, b = float(np.mean(y)), 0.0
    elif a < 0:
        a, b = 0.0, float(np.sum(x * y) / max(np.sum(x * x), 1e-12))
    pred = a + b * x
    ss = float(np.sum((y - y.mean()) ** 2))
    r2 = 1.0 - float(np.sum((y - pred) ** 2)) / ss if ss > 1e-15 else float('nan')
    return float(a), float(b), r2